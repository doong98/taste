-- 1. PostGIS 확장 활성화 (공간 데이터 및 좌표 계산 지원)
CREATE EXTENSION IF NOT EXISTS postgis;

-- 2. restaurants 테이블 생성 (이미 존재하는 경우 신규 컬럼 보강)
CREATE TABLE IF NOT EXISTS public.restaurants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(50) NOT NULL DEFAULT 'public_data',
    origin_id VARCHAR(100) NOT NULL,
    bizes_id VARCHAR(50),
    name VARCHAR(200) NOT NULL,
    category VARCHAR(50) NOT NULL,
    sub_category VARCHAR(100),
    road_address TEXT NOT NULL,
    jibun_address TEXT,
    phone VARCHAR(50),
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    location GEOGRAPHY(Point, 4326), -- PostGIS Point (SRID 4326: WGS84 좌표계)
    business_status VARCHAR(50),
    tags TEXT[] DEFAULT '{}',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. 기존 테이블에 컬럼 안전 추가 (Idempotent)
DO $$
BEGIN
    -- source 컬럼 추가
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='restaurants' AND column_name='source') THEN
        ALTER TABLE public.restaurants ADD COLUMN source VARCHAR(50) NOT NULL DEFAULT 'public_data';
    END IF;

    -- origin_id 컬럼 추가
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='restaurants' AND column_name='origin_id') THEN
        ALTER TABLE public.restaurants ADD COLUMN origin_id VARCHAR(100);
        UPDATE public.restaurants SET origin_id = bizes_id WHERE origin_id IS NULL AND bizes_id IS NOT NULL;
        ALTER TABLE public.restaurants ALTER COLUMN origin_id SET NOT NULL;
    END IF;

    -- location 컬럼 추가 (PostGIS Geography)
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='restaurants' AND column_name='location') THEN
        ALTER TABLE public.restaurants ADD COLUMN location GEOGRAPHY(Point, 4326);
    END IF;

    -- business_status 컬럼 추가
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='restaurants' AND column_name='business_status') THEN
        ALTER TABLE public.restaurants ADD COLUMN business_status VARCHAR(50);
    END IF;

    -- updated_at 컬럼 추가
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='restaurants' AND column_name='updated_at') THEN
        ALTER TABLE public.restaurants ADD COLUMN updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL;
    END IF;

    -- lat, lng NULL 허용
    ALTER TABLE public.restaurants ALTER COLUMN lat DROP NOT NULL;
    ALTER TABLE public.restaurants ALTER COLUMN lng DROP NOT NULL;
END $$;

-- 4. 출처(source)와 원본 ID(origin_id) 복합 유니크 제약조건
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'uq_restaurants_source_origin'
    ) THEN
        ALTER TABLE public.restaurants
        ADD CONSTRAINT uq_restaurants_source_origin UNIQUE (source, origin_id);
    END IF;
END $$;

-- 5. 기존 레코드의 location 값 갱신 (좌표 순서: ST_MakePoint(lng, lat))
-- ※ 중요: PostGIS의 Point 인자는 (X: 경도 lng, Y: 위도 lat) 순서입니다.
UPDATE public.restaurants
SET location = ST_SetSRID(ST_MakePoint(lng, lat), 4326)::geography
WHERE lat IS NOT NULL AND lng IS NOT NULL AND location IS NULL;

-- 6. 트리거: lat, lng 변경 시 location 및 updated_at 자동 갱신
CREATE OR REPLACE FUNCTION public.handle_restaurants_location_and_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    IF NEW.lat IS NOT NULL AND NEW.lng IS NOT NULL THEN
        -- 경도(lng)가 첫 번째, 위도(lat)가 두 번째
        NEW.location = ST_SetSRID(ST_MakePoint(NEW.lng, NEW.lat), 4326)::geography;
    ELSE
        NEW.location = NULL;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_restaurants_location_update ON public.restaurants;
CREATE TRIGGER trg_restaurants_location_update
BEFORE INSERT OR UPDATE ON public.restaurants
FOR EACH ROW
EXECUTE FUNCTION public.handle_restaurants_location_and_updated_at();

-- 7. 공간 인덱스(GIST) 및 일반 인덱스 생성
CREATE INDEX IF NOT EXISTS idx_restaurants_location ON public.restaurants USING GIST (location);
CREATE INDEX IF NOT EXISTS idx_restaurants_category ON public.restaurants (category);
CREATE INDEX IF NOT EXISTS idx_restaurants_name ON public.restaurants (name);

-- 8. PostGIS 기반 반경 내 주변 음식점 검색 RPC 함수
-- 거리 계산(직선거리, 미터), 반경 필터, 업종 필터, 이름 검색, 개수 제한 및 오름차순 정렬 수행
CREATE OR REPLACE FUNCTION public.search_nearby_restaurants(
    user_lat DOUBLE PRECISION,
    user_lng DOUBLE PRECISION,
    radius_meters INTEGER DEFAULT 3000,
    category_filter TEXT DEFAULT 'ALL',
    keyword_filter TEXT DEFAULT '',
    limit_count INTEGER DEFAULT 50
)
RETURNS TABLE (
    id BIGINT,
    source VARCHAR,
    origin_id VARCHAR,
    bizes_id VARCHAR,
    name VARCHAR,
    category VARCHAR,
    sub_category VARCHAR,
    road_address TEXT,
    jibun_address TEXT,
    phone VARCHAR,
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    business_status VARCHAR,
    tags TEXT[],
    distance_meters DOUBLE PRECISION, -- 직선거리 (미터 단위)
    created_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE
) AS $$
DECLARE
    user_point GEOGRAPHY;
BEGIN
    -- 사용자 위치 점 생성 (경도 user_lng, 위도 user_lat 순서)
    user_point := ST_SetSRID(ST_MakePoint(user_lng, user_lat), 4326)::geography;

    RETURN QUERY
    SELECT
        r.id,
        r.source,
        r.origin_id,
        r.bizes_id,
        r.name,
        r.category,
        r.sub_category,
        r.road_address,
        r.jibun_address,
        r.phone,
        r.lat,
        r.lng,
        r.business_status,
        r.tags,
        ROUND(ST_Distance(r.location, user_point)::numeric, 1)::DOUBLE PRECISION AS distance_meters,
        r.created_at,
        r.updated_at
    FROM public.restaurants r
    WHERE
        -- 1. 위치 좌표가 있는 음식점 대상
        r.location IS NOT NULL
        -- 2. 반경 필터 (ST_DWithin: 미터 단위 구면 직선거리 계산)
        AND (radius_meters IS NULL OR radius_meters <= 0 OR ST_DWithin(r.location, user_point, radius_meters))
        -- 3. 업종 필터
        AND (category_filter IS NULL OR category_filter = 'ALL' OR r.category = category_filter)
        -- 4. 키워드 검색 (상호명, 세부업종, 도로명 주소 매칭)
        AND (
            keyword_filter IS NULL OR keyword_filter = '' OR
            r.name ILIKE '%' || keyword_filter || '%' OR
            r.sub_category ILIKE '%' || keyword_filter || '%' OR
            r.road_address ILIKE '%' || keyword_filter || '%'
        )
    -- 직선거리 기준 가까운 순서 정렬
    ORDER BY distance_meters ASC
    LIMIT limit_count;
END;
$$ LANGUAGE plpgsql STABLE;

